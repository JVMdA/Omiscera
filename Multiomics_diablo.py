# ---------------------------------------------------------------------------
# Preparing the blocks
# ---------------------------------------------------------------------------

def prepare_blocks(mats: dict, cfg: dict) -> "tuple[dict, dict]":
    """mats: {omics: samples x features}, already aligned to the same samples. Per omics: optional log2(x + 1), drop
    constant / too-missing features, keep the most variable (same rules as Correlation / MOFA, so the tiles read a
    matrix alike). Scaling to zero mean / unit variance happens inside fit_diablo (every refit needs it fresh on
    its own training fold). Returns ({omics: matrix}, {omics: report})."""
    blocks, reports = {}, {}
    for o in [o for o in OMICS_ORDER if o in mats]:
        out, rep = mc.prepare_matrix(mats[o], bool(cfg["log2"]), float(cfg["max_missing"]), int(cfg["top_variance"]))
        if out.shape[1] < 2:
            raise ValueError(f"{OMICS_LABELS[o]}: fewer than two usable features remain after removing constant features and features "
                             f"missing in more than {float(cfg['max_missing']):.0%} of the samples.")
        blocks[o], reports[o] = out, rep
    if len(blocks) < 2:
        raise ValueError("DIABLO needs at least two omics (it links components ACROSS omics).")
    return blocks, reports


def check_groups(groups: np.ndarray, min_per_group: int = MIN_SAMPLES_PER_GROUP) -> "list[str]":
    """The usable group labels (at least min_per_group samples each), in sorted order. Raises if fewer than two."""
    g = np.asarray(groups, dtype=object)
    counts = pd.Series(g).value_counts()
    labels = sorted(str(x) for x in counts.index if x not in (None, "", "nan") and counts[x] >= min_per_group)
    if len(labels) < 2:
        raise ValueError(f"DIABLO needs at least two groups with {min_per_group} or more samples each; "
                         f"found {len(labels)} such group(s) (after dropping groups with fewer samples).")
    return labels


# ---------------------------------------------------------------------------
# Scaling (mixOmics' own scale.function: colMeans / column sample s.d., NaN-aware, a zero-variance column maps to 0)
# ---------------------------------------------------------------------------

def scale_block(df: pd.DataFrame) -> "tuple[np.ndarray, np.ndarray, np.ndarray]":
    """Centre and scale to unit variance, column by column, ignoring NaNs. Returns (scaled array, NaN kept as NaN;
    means; sds). A constant column (sd = 0) is mapped to all 0."""
    arr = df.to_numpy(dtype=float)
    mean = np.nanmean(arr, axis=0)
    n_obs = np.sum(~np.isnan(arr), axis=0)
    with np.errstate(all="ignore"):
        sd = np.sqrt(np.nansum((arr - mean) ** 2, axis=0) / np.maximum(n_obs - 1, 1))
    sd_safe = np.where(sd > 0, sd, 1.0)
    out = (arr - mean) / sd_safe
    out[:, sd == 0] = 0.0
    return out, mean, sd


def unmap(groups: np.ndarray, labels: list) -> np.ndarray:
    """One-hot dummy matrix (samples x groups), mixOmics' unmap()."""
    g = np.asarray(groups, dtype=object)
    return np.column_stack([(g == lab).astype(float) for lab in labels])


# ---------------------------------------------------------------------------
# One sGCCA component (mixOmics' sparse.mint.block_iteration, single study, horst scheme, regression mode - the
# only scheme / mode block.splsda uses). All of this works on "clean" blocks: NaN cells already replaced by 0, with
# a separate boolean mask remembering where. mixOmics always keeps R this way and re-zeroes it at the start of every
# component (deflation can write real numbers into a formerly-missing cell; it is zeroed again before the next
# component, never carried forward as information).
# ---------------------------------------------------------------------------

def l2norm(x: np.ndarray) -> np.ndarray:
    n = math.sqrt(float(x @ x))
    return x / n if n > 0 else x


def soft_threshold_keep(x: np.ndarray, keep: int) -> np.ndarray:
    """Zero the (p - keep) SMALLEST |x|; soft-threshold what remains by the largest zeroed |x| (mixOmics'
    soft_thresholding_L1(x, nx = p - keep)). Ties: R's rank(..., ties.method="max") gives every value in a tied
    group its group's HIGHEST rank, so a tied group is kept or dropped TOGETHER - replicated here exactly."""
    p = x.shape[0]
    keep = int(min(max(keep, 0), p))
    if keep >= p:
        return x.copy()
    if keep <= 0:
        return np.zeros_like(x)
    absx = np.abs(x)
    order = np.argsort(absx, kind="stable")           # ascending
    sorted_abs = absx[order]
    max_rank_sorted = np.arange(1, p + 1, dtype=float)
    for i in range(p - 2, -1, -1):                    # propagate the top rank of a tie backwards
        if sorted_abs[i] == sorted_abs[i + 1]:
            max_rank_sorted[i] = max_rank_sorted[i + 1]
    rank = np.empty(p)
    rank[order] = max_rank_sorted
    nx = p - keep
    selected = rank > nx
    if selected.all():
        return x.copy()
    threshold = absx[~selected].max()
    return np.where(selected, np.sign(x) * (absx - threshold), 0.0)


def _score_through(X_clean: np.ndarray, nan_mask: "np.ndarray | None", w_unit: np.ndarray) -> np.ndarray:
    """A block's per-sample score for its CURRENT (L2-unit-norm) loading: X_clean @ w, renormalised at a sample
    with a missing cell among the loaded features by the squared norm of the OBSERVED part of w (mixOmics' own
    rule - a fully observed sample divides by 1, since ||w|| = 1)."""
    num = X_clean @ w_unit
    if nan_mask is None or not nan_mask.any():
        return num
    rows = np.nonzero(nan_mask.any(axis=1))[0]
    denom = np.ones(X_clean.shape[0])
    for i in rows:
        miss = nan_mask[i]
        denom[i] = 1.0 - float(w_unit[miss] @ w_unit[miss])
    denom = np.where(denom > 1e-10, denom, 1.0)
    return num / denom


def _init_loadings(blocks_clean: list, Y: np.ndarray) -> list:
    """SVD initialisation (mixOmics init = "svd", block.splsda's default): for every X block, the first LEFT
    singular vector of (X_q^T Y); the outcome block's starting loading is the first RIGHT singular vector of the
    FIRST X block's crossproduct with Y (mixOmics takes it from block 1 only - confirmed from source, not an
    average over blocks)."""
    loadings = []
    first_v = None
    for X in blocks_clean:
        M = X.T @ Y
        U, _, Vt = np.linalg.svd(M, full_matrices=False)
        loadings.append(U[:, 0].copy())
        if first_v is None:
            first_v = Vt[0, :].copy()
    loadings.append(first_v)
    return loadings


def sgcca_component(blocks_clean: list, nan_masks: list, Y: np.ndarray, design: np.ndarray, keepX: list,
                    tol: float = 1e-6, max_iter: int = 100) -> dict:
    """One component of the iteration. blocks_clean: the J X-blocks (NaN already 0); Y: the outcome dummy block
    (block J, never missing); design: (J+1) x (J+1), 0 diagonal. keepX: features to keep per X block (the outcome
    block is never sparsified - mixOmics' own default, keepY = every column). Returns {"loadings": [J+1 arrays],
    "variates": (n, J+1), "iterations": int}."""
    J = len(blocks_clean)
    all_blocks = blocks_clean + [Y]
    loadings = [l2norm(w) for w in _init_loadings(blocks_clean, Y)]
    variates = np.column_stack([
        _score_through(all_blocks[q], nan_masks[q] if q < J else None, loadings[q]) for q in range(J + 1)
    ])
    it = 0
    for it in range(1, max_iter + 1):
        old = [w.copy() for w in loadings]
        for q in range(J + 1):
            Z = variates @ design[q]                  # horst scheme: Z_q = sum_q' design[q,q'] * score_q'
            nm = nan_masks[q] if q < J else None
            grad = all_blocks[q].T @ Z                 # NaN cells already 0 in all_blocks[q]
            if q < J:
                grad = soft_threshold_keep(grad, keepX[q])
            loadings[q] = l2norm(grad)
            variates[:, q] = _score_through(all_blocks[q], nm, loadings[q])
        diff = max(float((loadings[q] - old[q]) @ (loadings[q] - old[q])) for q in range(J + 1))
        if diff < tol:
            break
    return {"loadings": loadings, "variates": variates, "iterations": it}


def _deflate_X(X_clean: np.ndarray, nan_mask: "np.ndarray | None", t: np.ndarray) -> "tuple[np.ndarray, np.ndarray]":
    """Standard PLS deflation of an X block by its OWN score t (mixOmics' deflation()): p_j = (X_clean[:,j] . t) /
    denom_j, R_new = X_clean - outer(t, p); denom_j = t.t normally, or t.t restricted to the samples where feature
    j IS observed (mixOmics' per-FEATURE renormalisation - distinct from the per-SAMPLE one used for scores)."""
    numerator = X_clean.T @ t
    if nan_mask is None or not nan_mask.any():
        denom = np.full(X_clean.shape[1], float(t @ t))
    else:
        denom = np.full(X_clean.shape[1], float(t @ t))
        cols = np.nonzero(nan_mask.any(axis=0))[0]
        for j in cols:
            miss = nan_mask[:, j]
            denom[j] = float(t @ t) - float(t[miss] @ t[miss])
        denom = np.where(denom > 1e-10, denom, float(t @ t) if float(t @ t) > 0 else 1.0)
    p = numerator / denom
    R_new = X_clean - np.outer(t, p)
    if nan_mask is not None:
        R_new = np.where(nan_mask, 0.0, R_new)
    return R_new, p


def _deflate_Y_regression(Y_clean: np.ndarray, scores_X: list) -> np.ndarray:
    """mixOmics' regression-mode deflation of the outcome block: regress it on EACH X block's score separately
    (deflation() with no missing data - the outcome is always complete) and average the residuals."""
    J = len(scores_X)
    total = np.zeros_like(Y_clean)
    for t in scores_X:
        p = (Y_clean.T @ t) / float(t @ t)
        total = total + (Y_clean - np.outer(t, p))
    return total / J


def fit_diablo(blocks: dict, groups: np.ndarray, labels: list, cfg: dict, ncomp: int,
              keepX: "dict | None" = None) -> dict:
    """Fit DIABLO (block.splsda) for `ncomp` components. keepX: {omics: [keep per component]}; None/missing keeps
    every feature (a non-sparse block.plsda, used for the component-count search). Returns a dict: "omics" (order),
    "samples", "loadings" {omics: features x ncomp}, "variates" {omics: samples x ncomp}, "y_variates" (samples x
    ncomp), "iterations" (per component), "nan_masks", "means"/"sds" (per omics, for prediction), "Y_mean"/"Y_sd",
    "feature_names", "design", "group_labels", "keepX"."""
    omics = [o for o in OMICS_ORDER if o in blocks]
    J = len(omics)
    samples = list(blocks[omics[0]].index)
    n = len(samples)
    Y = unmap(groups, labels)
    design = np.full((J + 1, J + 1), float(cfg["design_value"]))
    design[:J, J] = 1.0
    design[J, :J] = 1.0
    np.fill_diagonal(design, 0.0)

    scaled, means, sds, nan_masks = {}, {}, {}, {}
    for o in omics:
        s, m, sd = scale_block(blocks[o])
        scaled[o], means[o], sds[o] = s, m, sd
        mask = np.isnan(s)
        nan_masks[o] = mask if mask.any() else None
    Y_mean = Y.mean(axis=0)
    Y_sd = Y.std(axis=0, ddof=1)
    Y_sd_safe = np.where(Y_sd > 0, Y_sd, 1.0)
    Y_scaled = (Y - Y_mean) / Y_sd_safe

    kx = {o: list(keepX.get(o)) if keepX and o in keepX else [blocks[o].shape[1]] * ncomp for o in omics}

    all_loadings = {o: np.zeros((blocks[o].shape[1], ncomp)) for o in omics}
    all_variates = {o: np.zeros((n, ncomp)) for o in omics}
    y_variates = np.zeros((n, ncomp))
    iters = []
    # the ORIGINAL (un-deflated) scaled + NaN-zeroed matrices: prediction's P matrix is always computed against
    # these, never against the progressively deflated residuals used while fitting (mixOmics' own convention).
    X_clean = {o: np.where(nan_masks[o], 0.0, scaled[o]) if nan_masks[o] is not None else scaled[o].copy() for o in omics}
    R = {o: X_clean[o].copy() for o in omics}
    RY = Y_scaled.copy()
    for h in range(ncomp):
        for o in omics:                              # re-zero the missing cells before every component (mixOmics' own guard)
            if nan_masks[o] is not None:
                R[o] = np.where(nan_masks[o], 0.0, R[o])
        keep_h = [int(kx[o][h]) for o in omics]
        comp = sgcca_component([R[o] for o in omics], [nan_masks[o] for o in omics], RY, design, keep_h)
        iters.append(comp["iterations"])
        for i, o in enumerate(omics):
            all_loadings[o][:, h] = comp["loadings"][i]
            all_variates[o][:, h] = comp["variates"][:, i]
        y_variates[:, h] = comp["variates"][:, J]
        if h < ncomp - 1:
            scores = [comp["variates"][:, i] for i in range(J)]
            for i, o in enumerate(omics):
                R[o], _ = _deflate_X(R[o], nan_masks[o], scores[i])
            RY = _deflate_Y_regression(RY, scores)
    return {"omics": omics, "group_labels": labels, "samples": samples, "loadings": all_loadings,
            "variates": all_variates, "y_variates": y_variates, "iterations": iters, "nan_masks": nan_masks,
            "means": means, "sds": sds, "Y_mean": Y_mean, "Y_sd": Y_sd_safe, "X_clean": X_clean, "Y_scaled": Y_scaled,
            "feature_names": {o: list(blocks[o].columns) for o in omics}, "design": design, "ncomp": ncomp, "keepX": kx}


# ---------------------------------------------------------------------------
# Predicting a new sample's score and class (mixOmics' predict.block.pls / internal_predict.DA)
# ---------------------------------------------------------------------------

def predict_scores(fit: dict, newdata_raw: dict) -> "tuple[dict, dict]":
    """newdata_raw: {omics: samples x the SAME features, in the SAME order, as fit["feature_names"][omics]} - raw
    (unscaled) values, scaled here with the TRAINING means/sds. Returns (t_pred, Y_hat):
    t_pred[omics] = (n_new, ncomp) scores comparable to fit["variates"][omics]; Y_hat[omics] = (n_new, n_groups,
    ncomp) the regression-based prediction of the group dummy (near 0/1), used by max.dist.

    mixOmics' own formulas (predict.block.pls), both against the TRAINING data: P = X_clean_train^T @ T_train
    (features x ncomp), C = Y_scaled_train^T @ T_train (groups x ncomp), W = the fitted loadings (features x ncomp,
    already unit-norm per column). For h components: B_h = W[:,:h] @ inv(P[:,:h]^T @ W[:,:h]) @ C[:,:h]^T;
    Y_hat[:,:,h] = (newdata_scaled @ B_h) * Y_sd + Y_mean. t_pred uses ALL ncomp columns of W/P at once, then
    rescales each column h by ||T_train[:,h]||^2 (mixOmics' own correction, not a textbook PLS score)."""
    omics = fit["omics"]
    ncomp = fit["ncomp"]
    n_new = len(next(iter(newdata_raw.values())))
    t_pred, Y_hat = {}, {}
    for o in omics:
        mean, sd = fit["means"][o], fit["sds"][o]
        sd_safe = np.where(sd > 0, sd, 1.0)
        raw = newdata_raw[o].reindex(columns=fit["feature_names"][o]).to_numpy(dtype=float)
        scaled = (raw - mean) / sd_safe
        scaled[:, sd == 0] = 0.0
        scaled = np.where(np.isnan(scaled), 0.0, scaled)       # mixOmics: NaN in newdata -> 0, no further renormalisation
        T_train, W = fit["variates"][o], fit["loadings"][o]
        Pmat = fit["X_clean"][o].T @ T_train
        Cmat = fit["Y_scaled"].T @ T_train
        Yh = np.zeros((n_new, Cmat.shape[0], ncomp))
        for h in range(1, ncomp + 1):
            B_h = W[:, :h] @ np.linalg.solve(Pmat[:, :h].T @ W[:, :h], Cmat[:, :h].T)
            Yh[:, :, h - 1] = (scaled @ B_h) * fit["Y_sd"] + fit["Y_mean"]
        Y_hat[o] = Yh
        t_raw = scaled @ W @ np.linalg.solve(Pmat.T @ W, np.eye(ncomp))
        col_scale = (T_train ** 2).sum(axis=0)              # ||T_train[:,h]||^2 for every h
        t_pred[o] = t_raw * col_scale[np.newaxis, :]
    return t_pred, Y_hat


def classify_max_dist(fit: dict, Y_hat: dict) -> dict:
    """{omics: (n_new, ncomp) array of group INDEX (into fit["group_labels"]), the highest Y_hat value per sample
    and component; a tie keeps every tied index as a tuple (rare with continuous values)."""
    out = {}
    for o in fit["omics"]:
        Yh = Y_hat[o]
        n_new, _, ncomp = Yh.shape
        cls = np.empty((n_new, ncomp), dtype=object)
        for h in range(ncomp):
            for i in range(n_new):
                row = Yh[i, :, h]
                best = np.nonzero(row == row.max())[0]
                cls[i, h] = tuple(best)
        out[o] = cls
    return out


def _centroids_by_group(fit: dict, groups_train: np.ndarray) -> dict:
    """{omics: (n_groups, ncomp) training mean score per group}."""
    Yprim = unmap(groups_train, fit["group_labels"])
    out = {}
    for o in fit["omics"]:
        T = fit["variates"][o]
        out[o] = np.array([T[Yprim[:, k] == 1].mean(axis=0) for k in range(len(fit["group_labels"]))])
    return out


def classify_centroids_dist(fit: dict, t_pred: dict, groups_train: np.ndarray) -> dict:
    """{omics: (n_new, ncomp) group-index tuples}: nearest class-mean score in Euclidean distance, using the first
    h components cumulatively (mixOmics' centroids.dist)."""
    G = _centroids_by_group(fit, groups_train)
    out = {}
    for o in fit["omics"]:
        t = t_pred[o]
        n_new, ncomp = t.shape
        cls = np.empty((n_new, ncomp), dtype=object)
        for h in range(1, ncomp + 1):
            Gh = G[o][:, :h]
            for i in range(n_new):
                d = ((t[i, :h][np.newaxis, :] - Gh) ** 2).sum(axis=1)
                best = np.nonzero(d == d.min())[0]
                cls[i, h - 1] = tuple(best)
        out[o] = cls
    return out


def classify_mahalanobis_dist(fit: dict, t_pred: dict, groups_train: np.ndarray) -> dict:
    """{omics: (n_new, ncomp) group-index tuples}: mixOmics' mahalanobis.dist, replicated EXACTLY (for h > 1 this is
    NOT the textbook Mahalanobis distance - mixOmics sums the squared ROW of (x - G) @ Sr^-1 @ (x - G)^T, including
    cross terms with the other classes, not just the diagonal; kept as-is so the result matches mixOmics)."""
    G = _centroids_by_group(fit, groups_train)
    Yprim = unmap(groups_train, fit["group_labels"])
    out = {}
    for o in fit["omics"]:
        t = t_pred[o]
        T_train = fit["variates"][o]
        n_new, ncomp = t.shape
        q = len(fit["group_labels"])
        cls = np.empty((n_new, ncomp), dtype=object)
        for h in range(1, ncomp + 1):
            Gh = G[o][:, :h]
            Xe = Yprim @ Gh
            Xr = T_train[:, :h] - Xe
            Sr = (Xr.T @ Xr) / Yprim.shape[0]
            Sr_inv = np.linalg.inv(Sr) if h > 1 else np.array([[1.0 / Sr[0, 0]]]) if Sr[0, 0] != 0 else np.array([[0.0]])
            for i in range(n_new):
                x = np.tile(t[i, :h], (q, 1))
                if h > 1:
                    mat = (x - Gh) @ Sr_inv @ (x - Gh).T
                    d = (mat ** 2).sum(axis=1)
                else:
                    # a positive scalar factor never changes which class is closest (h > 1's Sr_inv is a MATRIX,
                    # so it can; tested against the mixOmics fixture, both h = 1 and h = 2) - kept for the exact
                    # same "d" values mixOmics itself reports, not because it could change which class wins here.
                    d = Sr_inv[0, 0] * (x[:, 0] - Gh[:, 0]) ** 2
                best = np.nonzero(d == d.min())[0]
                cls[i, h - 1] = tuple(best)
        out[o] = cls
    return out


def majority_vote(class_by_omics: dict) -> np.ndarray:
    """(n_new, ncomp) group-index tuples: the class most omics agree on per sample and component; a tie (no unique
    winner) gives None (mixOmics' own NA-on-tie)."""
    omics = list(class_by_omics)
    sample_cls = class_by_omics[omics[0]]
    n_new, ncomp = sample_cls.shape
    out = np.empty((n_new, ncomp), dtype=object)
    for i in range(n_new):
        for h in range(ncomp):
            votes = []
            for o in omics:
                for idx in class_by_omics[o][i, h]:
                    votes.append(idx)
            counts = pd.Series(votes).value_counts()
            top = counts[counts == counts.max()].index.tolist()
            out[i, h] = top[0] if len(top) == 1 else None
    return out


def weighted_vote(fit: dict, class_by_omics: dict) -> np.ndarray:
    """(n_new, ncomp) group-index tuples, votes weighted by how well each omics' components tracked the outcome's
    OWN fitted component on the training data (mixOmics' get.weights: per-component correlation of a block's score
    with the outcome block's score, averaged over components into ONE scalar weight per omics, applied to every
    component's vote)."""
    omics = fit["omics"]
    weight_of = {}
    for o in omics:
        T, Ty = fit["variates"][o], fit["y_variates"]
        per_comp = [np.corrcoef(T[:, k], Ty[:, k])[0, 1] for k in range(fit["ncomp"])]
        weight_of[o] = float(np.nanmean(per_comp))
    sample_cls = class_by_omics[omics[0]]
    n_new, ncomp = sample_cls.shape
    out = np.empty((n_new, ncomp), dtype=object)
    for i in range(n_new):
        for h in range(ncomp):
            tally: dict = {}
            for o in omics:
                for idx in class_by_omics[o][i, h]:
                    tally[idx] = tally.get(idx, 0.0) + weight_of[o] / len(class_by_omics[o][i, h])
            best = max(tally.values())
            top = [k for k, v in tally.items() if v == best]
            out[i, h] = top[0] if len(top) == 1 else None
    return out, weight_of


# ---------------------------------------------------------------------------
# Balanced error rate (mixOmics' own definition: mean over classes of the class's own misclassification rate)
# ---------------------------------------------------------------------------

def confusion_counts(pred_idx: np.ndarray, true_idx: np.ndarray, n_groups: int) -> np.ndarray:
    """(n_groups, n_groups) confusion matrix, rows = predicted, columns = true (mixOmics' table(pred, true)).
    A None prediction (a tie) is added to no cell at all - never the diagonal, so (via error_rates, which counts
    the true-class TOTAL independently of this matrix) it always counts as an error for its true class, matching
    mixOmics' own NA handling."""
    mat = np.zeros((n_groups, n_groups), dtype=float)
    for p, t in zip(pred_idx, true_idx):
        if p is not None:
            mat[p, t] += 1
    return mat


def explained_variance(fit: dict) -> dict:
    """{omics: [AVE per component]} - mixOmics' own AVE_X: for component h, (sum_j (X_clean[:,j] . T[:,h])^2) /
    (T[:,h].T[:,h]) / ||X_clean||_F^2, i.e. how much of the block's OWN total (squared Frobenius) variance its score
    alone accounts for. Exact to float64 precision against mixOmics (checked in tests/test_multiomics_diablo.py).
    A block with MISSING values gives NaN for every component - mixOmics' own Check.entry.single cannot rank-check
    data with NaN and leaves AVE_X undefined there; replicated here rather than inventing a number mixOmics itself
    does not report. (The outcome block's own AVE is not computed: mixOmics does not surface it either, and the one
    formula that looked plausible for it drifted from the reference by ~1e-7 on data this module does not need it
    for - not reliable enough to show as an exact number.)"""
    out = {}
    for o in fit["omics"]:
        if fit["nan_masks"][o] is not None:
            out[o] = [float("nan")] * fit["ncomp"]
            continue
        X = fit["X_clean"][o]
        norm2 = float((X ** 2).sum())
        vals = []
        for h in range(fit["ncomp"]):
            t = fit["variates"][o][:, h]
            a = X.T @ t
            vals.append(float((a @ a) / (t @ t) / norm2))
        out[o] = vals
    return out


def _combine(fit: dict, t_pred: dict, Y_hat: dict, groups_train: np.ndarray, distance: str) -> "tuple[np.ndarray, dict]":
    """(n_new, ncomp) group-index predictions and the per-block weights, for ONE named distance, combined by
    WEIGHTED vote - the combination tune.block.splsda itself optimises by default (mixOmics' dist argument picks
    the DISTANCE; the vote is always weighted in the tuning step, majority vote is an extra diagnostic only)."""
    if distance == "max.dist":
        cls = classify_max_dist(fit, Y_hat)
    elif distance == "centroids.dist":
        cls = classify_centroids_dist(fit, t_pred, groups_train)
    elif distance == "mahalanobis.dist":
        cls = classify_mahalanobis_dist(fit, t_pred, groups_train)
    else:
        raise ValueError(f"Unknown distance {distance!r}.")
    return weighted_vote(fit, cls)


# ---------------------------------------------------------------------------
# Cross-validation: stratified, repeated folds; BER is computed on the POOLED held-out predictions of one repeat
# (mixOmics' own convention - every sample is held out exactly once per repeat, predictions are put back in their
# original order, and ONE confusion matrix covers the whole repeat), then averaged over repeats.
# ---------------------------------------------------------------------------

def stratified_folds(groups: np.ndarray, n_folds: int, seed: int) -> np.ndarray:
    """A fold index (0..n_folds-1) per sample, balanced within each group (mixOmics' own stratified CV)."""
    g = np.asarray(groups, dtype=object)
    fold = np.full(len(g), -1, dtype=int)
    rng = np.random.RandomState(seed)
    for lab in sorted(set(g.tolist())):
        idx = np.nonzero(g == lab)[0]
        rng.shuffle(idx)
        for i, s in enumerate(idx):
            fold[s] = i % n_folds
    return fold


def _cv_predictions(blocks: dict, groups: np.ndarray, labels: list, cfg: dict, ncomp: int, keepX: "dict | None",
                    fold: np.ndarray, n_folds: int, distance: str) -> "tuple[np.ndarray, np.ndarray]":
    """One repeat: fit on every fold-held-out training set, predict its own held-out fold, pool the predictions back
    into the ORIGINAL sample order. Returns (pred_idx, true_idx), both length n, pred entries may be None (a tie)."""
    omics = list(blocks)
    n = len(groups)
    pred_idx = np.empty(n, dtype=object)
    for f in range(n_folds):
        test_mask = fold == f
        train_mask = ~test_mask
        train_blocks = {o: blocks[o].iloc[train_mask] for o in omics}
        train_groups = groups[train_mask]
        train_labels = check_groups(train_groups, min_per_group=1)
        if sorted(train_labels) != sorted(labels):
            # a fold emptied a group entirely (can happen with a tiny group): skip this fold's samples, counted as untested
            continue
        test_blocks = {o: blocks[o].iloc[test_mask] for o in omics}
        fit = fit_diablo(train_blocks, train_groups, labels, cfg, ncomp, keepX=keepX)
        t_pred, Y_hat = predict_scores(fit, test_blocks)
        cls, _ = _combine(fit, t_pred, Y_hat, train_groups, distance)
        pred_idx[test_mask] = cls[:, ncomp - 1]
    true_idx = np.array([labels.index(str(g)) for g in groups])
    return pred_idx, true_idx


def cv_ber(blocks: dict, groups: np.ndarray, labels: list, cfg: dict, ncomp: int, keepX: "dict | None",
          n_folds: int, n_repeats: int, seed: int, distance: str, progress=None) -> dict:
    """Repeated stratified CV. Returns {"BER": mean, "BER_sd", "ER": mean, "ER_sd", "per_repeat": [BER per repeat]}."""
    n_groups = len(labels)
    bers, ers = [], []
    for r in range(n_repeats):
        fold = stratified_folds(groups, n_folds, seed + r)
        pred_idx, true_idx = _cv_predictions(blocks, groups, labels, cfg, ncomp, keepX, fold, n_folds, distance)
        err = error_rates(pred_idx, true_idx, n_groups)
        bers.append(err["BER"])
        ers.append(err["ER"])
        if progress:
            progress((r + 1) / n_repeats)
    return {"BER": float(np.mean(bers)), "BER_sd": float(np.std(bers, ddof=1)) if n_repeats > 1 else 0.0,
            "ER": float(np.mean(ers)), "ER_sd": float(np.std(ers, ddof=1)) if n_repeats > 1 else 0.0,
            "per_repeat": bers}


def tune_components(blocks: dict, groups: np.ndarray, labels: list, cfg: dict, progress=None) -> dict:
    """How many components are worth keeping: cross-validated BER of a NON-SPARSE fit (every feature kept - the
    question here is only "how many components", not "which features"), for ncomp = 1 .. cfg['max_components'].
    Returns {"per_ncomp": [{"ncomp", "BER", "BER_sd"}], "chosen": the smallest ncomp whose BER is not worse than the
    best one by more than its own standard deviation - the one-standard-error rule, so a later component that does
    not clearly help is not kept just because its point estimate is marginally lower}."""
    max_n = int(cfg["max_components"])
    rows = []
    for i, ncomp in enumerate(range(1, max_n + 1)):
        res = cv_ber(blocks, groups, labels, cfg, ncomp, None, int(cfg["n_folds"]), int(cfg["n_repeats"]), int(cfg["seed"]),
                     str(cfg["distance"]), progress=(lambda f, i=i: progress((i + f) / max_n)) if progress else None)
        rows.append({"ncomp": ncomp, "BER": res["BER"], "BER_sd": res["BER_sd"]})
    best = min(r["BER"] for r in rows)
    best_sd = next(r["BER_sd"] for r in rows if r["BER"] == best)
    chosen = next(r["ncomp"] for r in rows if r["BER"] <= best + best_sd)
    return {"per_ncomp": rows, "chosen": chosen}


def tune_keepX(blocks: dict, groups: np.ndarray, labels: list, cfg: dict, ncomp: int, progress=None) -> dict:
    """keepX, one component at a time (mixOmics' own greedy convention - not every combination over every component
    at once, which would be the grid size to the power of ncomp): for component h, with the already-chosen keepX of
    components 1..h-1 held fixed, cross-validate every grid combination across the omics for component h alone and
    keep the one with the lowest BER. Returns {"keepX": {omics: [chosen per component]}, "per_component":
    [{"ncomp", "grid": [{"keepX": {...}, "BER", "BER_sd"}], "chosen": {...}}]}."""
    omics = list(blocks)
    grid = [int(x) for x in cfg["keepX_grid"]]
    chosen: dict = {o: [] for o in omics}
    per_component = []
    n_combos = len(grid) ** len(omics)
    for h in range(ncomp):
        candidates = _grid_combinations(omics, grid)
        results = []
        for j, combo in enumerate(candidates):
            kx = {o: chosen[o] + [combo[o]] for o in omics}
            res = cv_ber(blocks, groups, labels, cfg, h + 1, kx, int(cfg["n_folds"]), int(cfg["n_repeats"]), int(cfg["seed"]),
                         str(cfg["distance"]),
                         progress=(lambda f, h=h, j=j: progress((h * n_combos + j + f) / (ncomp * n_combos))) if progress else None)
            results.append({"keepX": dict(combo), "BER": res["BER"], "BER_sd": res["BER_sd"]})
        best = min(results, key=lambda r: r["BER"])
        for o in omics:
            chosen[o].append(best["keepX"][o])
        per_component.append({"ncomp": h + 1, "grid": results, "chosen": dict(best["keepX"])})
    return {"keepX": chosen, "per_component": per_component}


def _grid_combinations(omics: list, grid: list) -> "list[dict]":
    combos = [{}]
    for o in omics:
        combos = [dict(c, **{o: v}) for c in combos for v in grid]
    return combos


def permutation_test_ber(blocks: dict, groups: np.ndarray, labels: list, cfg: dict, ncomp: int, keepX: dict,
                         observed_ber: float, n_perm: int = 20, seed: int = 0, progress=None) -> dict:
    """Is the observed cross-validated BER better than this PARTICULAR dataset's own chance structure, not just
    better than 0.5 in the abstract? With few samples a single run's BER depends a lot on which samples happened to
    land in which fold (checked directly: averaged over independent noise datasets the CV error is unbiased at 0.5,
    but on one FIXED dataset a single label permutation can swing from ~0.3 to ~0.7 just by chance). So: refit and
    re-cross-validate (1 repeat each, to keep this affordable) on `n_perm` versions of the SAME data with the group
    labels randomly permuted (keepX and ncomp held at the already-chosen values - this asks only whether the LABELS
    matter, not whether more tuning would help); the empirical p-value is the fraction of permuted BERs that are AT
    LEAST AS GOOD (as low) as the observed one. Returns {"p_value", "null_bers", "observed_ber"}."""
    rng = np.random.RandomState(seed)
    null_bers = []
    for i in range(n_perm):
        perm = groups.copy()
        rng.shuffle(perm)
        fold = stratified_folds(perm, int(cfg["n_folds"]), seed + 1000 + i)
        pred_idx, true_idx = _cv_predictions(blocks, perm, labels, cfg, ncomp, keepX, fold, int(cfg["n_folds"]), str(cfg["distance"]))
        null_bers.append(error_rates(pred_idx, true_idx, len(labels))["BER"])
        if progress:
            progress((i + 1) / n_perm)
    p = (1 + sum(1 for b in null_bers if b <= observed_ber)) / (n_perm + 1)     # +1: the observed labelling counts as one of the permutations
    return {"p_value": float(p), "null_bers": null_bers, "observed_ber": float(observed_ber), "n_perm": n_perm}


def error_rates(pred_idx: np.ndarray, true_idx: np.ndarray, n_groups: int) -> dict:
    """{"BER", "ER", "per_class": [...]} from one column of predictions. BER = mean, over the TRUE classes present,
    of (misclassified in that class) / (total of that class) - mixOmics' Overall.BER; ER = overall error rate. The
    per-class TOTAL is the true class count (every sample, whether or not it got a prediction), not the confusion
    matrix's own column sum - a tied (None) prediction contributes nothing to the diagonal but still counts in its
    true class's total, so it always counts as an error (matching R's table()-based Overall.BER, where summary(Y)
    is the true label vector, not derived from a table that an NA prediction would simply be absent from)."""
    mat = confusion_counts(pred_idx, true_idx, n_groups)
    totals = np.bincount(true_idx, minlength=n_groups).astype(float)
    correct = np.diag(mat)
    per_class = np.where(totals > 0, 1.0 - correct / np.where(totals > 0, totals, 1.0), np.nan)
    return {"BER": float(np.nanmean(per_class)), "ER": float(1.0 - correct.sum() / max(totals.sum(), 1.0)),
            "per_class": per_class.tolist(), "confusion": mat}


