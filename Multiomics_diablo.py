"""Multi-omics - DIABLO / Multiblock Integration (sixth and last tile of the Multi-omics submodule).

QUESTION ANSWERED
-----------------
Several omics measured on the SAME samples, and a GROUP label for each sample (control / treated, two or more).
DIABLO (Data Integration Analysis for Biomarker discovery using Latent cOmponents; Singh et al. 2019, Bioinformatics
35:3055, mixOmics' block.splsda) finds a few COMPONENTS per omics that are:
  - correlated with one another ACROSS the omics (the omics "agree" on these components), and
  - discriminant: they separate the groups,
while keeping only a SMALL, chosen number of features per omics per component (sparse). It is the SUPERVISED
counterpart of MOFA (unsupervised, no groups): where MOFA asks "what varies together", DIABLO asks "what, together,
tells the groups apart".

THE CENTRAL PITFALL, AND WHY THE RESULT IS A CROSS-VALIDATED NUMBER
---------------------------------------------------------------------
A sparse supervised model fitted and judged on the SAME samples ALWAYS looks like it separates the groups - that is
what it was optimised to do, not evidence of a real biological signal. The only honest number is how well the model
classifies samples it did NOT see: repeated, stratified cross-validation chooses how many features to keep per omics
and component (mixOmics' tune.block.splsda) and reports the cross-validated BALANCED ERROR RATE (BER = the mean,
over the groups, of each group's own misclassification rate - robust to unequal group sizes, unlike plain accuracy).
A small BER on held-out folds is the finding; a perfect fit on the training data is not.

WHAT IS HERE AND WHAT IS NOT
----------------------------
DIABLO's only published implementation is the R package mixOmics (Rohart et al. 2017, PLoS Comput Biol 13:e1005752).
Its algorithm - sparse generalized canonical correlation analysis (sGCCA; Tenenhaus et al. 2014, Biostatistics 15:569),
with the outcome as an extra "block" (regression mode) - is implemented here in pure Python, re-derived from mixOmics'
OWN SOURCE (not from the paper alone, which does not specify every numerical choice: the SVD initialisation, which
block's score initialises the outcome's weights, the exact soft-thresholding rule, which score deflates which block in
regression mode, the renormalisation used at a missing cell, the three classification distances). Every one of those
choices is checked against a local mixOmics run (tests/test_multiomics_diablo.py; fixtures regenerated by
tests/generate_diablo_examples.py + an R script, not shipped - see tests/r_reference/README.txt). No R is needed to
RUN Omiscera; it is needed only to regenerate the test fixtures.

THE MODEL, PLAINLY
-------------------
  - Per omics, one COMPONENT per round: a weighted sum of a few of its features (the "loading"), chosen so the
    resulting per-sample score (i) is as correlated as the DESIGN says it should be with the other omics' scores and
    with the outcome, and (ii) keeps only `keepX` features (the rest get weight exactly 0, via soft-thresholding).
  - DESIGN: how strongly each pair of omics is linked in the optimisation (0 = not linked, only to the outcome; 1 =
    fully linked). The outcome is always linked to every omics at 1 (mixOmics' own convention, confirmed from its
    source); the omics-to-omics link is a setting (default 0.1, the value the DIABLO paper's own case studies use -
    a compromise: 0 drops omics agreement and tends to pick features specific to each omics separately rather than a
    shared signal; 1 fully couples the omics and can pick features correlated with each other rather than the group).
  - keepX (how many features per omics per component) is TUNED by cross-validation over a grid (never typed in
    blind): the combination with the lowest cross-validated BER is kept, one component at a time.
  - CLASSIFYING a sample: each omics' component gives it a score; the predicted class comes from a DISTANCE in score
    space to each class's training centroid (max.dist: the highest value of a per-component linear prediction of the
    class dummy; centroids.dist: nearest class-mean score, Euclidean; mahalanobis.dist: the same, scaled by the
    within-class score covariance) - mixOmics' own three rules, all three are kept and shown, never only one chosen
    silently. The omics VOTE on the class (majority; or weighted by how well each omics' components tracked the
    outcome on the training data).

MISSING VALUES AND SAMPLE SIZE
-------------------------------
Features missing in more than half of the samples are dropped (as the other Multi-omics methods); remaining missing
cells are handled the way mixOmics itself handles them: a sample's score, and a feature's deflation coefficient, are
computed from the cells that ARE observed and renormalised accordingly - never imputed. DIABLO needs at least two
groups with enough samples for cross-validation: fewer than MIN_SAMPLES_PER_GROUP in a group is refused, fewer than
WARN_SAMPLES_PER_GROUP is warned about.
"""

