def selected_features(fit: dict) -> dict:
    """{omics: [feature ids selected by ANY kept component]} - the union over components, in the order the
    features appear in the block (not by weight: a feature is either kept or it is not)."""
    out = {}
    for o in fit["omics"]:
        w = fit["loadings"][o]
        keep = np.nonzero((w != 0).any(axis=1))[0]
        out[o] = [fit["feature_names"][o][i] for i in keep]
    return out


def _bh(p) -> np.ndarray:
    p = np.asarray(p, dtype=float)
    q = np.full(p.shape, np.nan)
    ok = np.isfinite(p)
    pv = p[ok]
    m = len(pv)
    if m == 0:
        return q
    order = np.argsort(pv)
    adj = np.minimum.accumulate((pv[order] * m / (np.arange(m) + 1))[::-1])[::-1]
    out = np.empty(m)
    out[order] = np.minimum(adj, 1.0)
    q[ok] = out
    return q


def selected_feature_enrichment(selected_keys: set, background_keys: set, term_map: dict, min_size: int = 10,
                                max_size: int = 500) -> pd.DataFrame:
    """Over-representation (one-sided Fisher exact) of the SELECTED features among the MEASURED (background)
    features of that omics, pathway by pathway - exactly the convention the single-omics ORA tiles use
    (Multiomics_module._per_pathway_pvalues, imported rather than re-implemented), applied here to DIABLO's
    selected-feature set instead of a differential-expression list. Benjamini-Hochberg over the pathways tested.
    Returns a DataFrame sorted by FDR: Term ID, Term Name, k (selected hits), K (pathway size, restricted to the
    background), n (selected set size), N (background size), p-value, FDR, Fold Enrichment, Members (which selected
    features hit the term)."""
    from Multiomics_module import _per_pathway_pvalues

    res = _per_pathway_pvalues(term_map, selected_keys, background_keys, min_size, max_size)
    terms = res["terms"]
    cols = ["Term ID", "Term Name", "k", "K", "n", "N", "p-value", "FDR", "Fold Enrichment", "Members"]
    if not terms:
        return pd.DataFrame(columns=cols)
    rows = [{"Term ID": tid, "Term Name": info["name"], "k": info["k"], "K": info["K"], "n": info["n"], "N": info["N"],
            "p-value": info["p"], "Fold Enrichment": info["fold"], "Members": ", ".join(sorted(map(str, info["overlap"])))}
           for tid, info in terms.items()]
    df = pd.DataFrame(rows)
    df["FDR"] = _bh(df["p-value"].to_numpy())
    return df.sort_values(by=["FDR", "p-value", "Term ID"], kind="stable").reset_index(drop=True)[cols]
